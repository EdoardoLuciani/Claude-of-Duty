import { launchChromium } from './lib/browser-harness.mjs';
const target = new URL(process.argv[2]);
target.searchParams.set('capture', '1');
const b = await launchChromium({ headless:true, args:['--ignore-gpu-blocklist','--mute-audio'] });
const p = await b.newPage({ viewport:{width:1600,height:900} });
const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>m.type()==='error'&&errs.push(m.text()));
const t0=Date.now();
const resp = await p.goto(target.href,{waitUntil:'domcontentloaded',timeout:60000});
await p.waitForFunction('window.__READY__===true',null,{timeout:90000});
const bootMs = Date.now()-t0;
await p.evaluate(()=>window.__APPLY_SHOT__('hero'));
