await p.screenshot({path:'shots/live-verify.png'});
const info = await p.evaluate(()=>window.__RENDER_INFO__);
console.log(JSON.stringify({url:target.href, http:resp.status(), bootMs, ready:true, calls:info.calls, tris:info.tris, errors:errs.slice(0,6)},null,2));
